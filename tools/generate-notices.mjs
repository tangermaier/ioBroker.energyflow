// Generates THIRD_PARTY_NOTICES.md from the production dependency trees that end up in a release:
// - adapter backend (root package, production dependencies)
// - vis-2 widgets (only the runtime libraries bundled into widgets/, not the build tooling)
// - 3D scene (production dependencies bundled into www/)
// Fails if a license is not on the GPL-3.0-compatible allowlist, so an incompatible new dependency
// is noticed before a release. Usage: node tools/generate-notices.mjs [--check]
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

/** GPL-3.0-compatible licenses accepted without review. */
const ALLOWED = new Set(["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD", "CC0-1.0", "Unlicense", "Python-2.0", "BlueOak-1.0.0", "Zlib"]);

/** Individually reviewed packages whose license field is not a clean SPDX id. Key: name@version. */
const REVIEWED = {
	// Transitive dependency of @iobroker/adapter-core (via @iobroker/js-controller-common-db), not
	// bundled by this adapter. License field "BSD" without version and no license file - every BSD
	// variant is permissive and GPL-3.0-compatible.
	"readline@1.3.0": "BSD (unversioned, reviewed)",
};

const PARTS = [
	{ name: "Adapter (backend)", dir: ".", args: ["ls", "--omit=dev", "--all", "--json"] },
	{
		name: "vis-2 widgets (bundled runtime libraries)",
		dir: "src-widgets",
		args: ["ls", "react", "react-dom", "@mui/material", "@emotion/react", "@emotion/styled", "--all", "--json"],
	},
	{ name: "3D scene (bundled)", dir: "src-scene", args: ["ls", "--omit=dev", "--all", "--json"] },
];

function npm(dir, args) {
	const cmd = process.platform === "win32" ? "npm.cmd" : "npm";
	try {
		return JSON.parse(
			execFileSync(cmd, args, { cwd: join(ROOT, dir), encoding: "utf8", shell: process.platform === "win32", maxBuffer: 64 * 1024 * 1024 }),
		);
	} catch (e) {
		// npm ls exits non-zero on peer-dependency warnings but still prints the tree
		return JSON.parse(e.stdout);
	}
}

function collect(tree, out) {
	for (const [name, info] of Object.entries(tree.dependencies ?? {})) {
		if (info.version && !out.has(`${name}@${info.version}`)) {
			out.set(`${name}@${info.version}`, { name, version: info.version });
		}
		collect(info, out);
	}
}

function licenseOf(pkg) {
	const l = pkg.license ?? pkg.licenses;
	if (typeof l === "string") {
		return l;
	}
	if (Array.isArray(l)) {
		return l.map(x => x.type ?? x).join(" OR ");
	}
	return l?.type ?? "UNKNOWN";
}

/**
 * True if an SPDX expression is acceptable (every OR-alternative set must contain one allowed id).
 *
 * @param expr
 */
function allowed(expr) {
	const clean = expr.replace(/[()]/g, "");
	return clean.split(/\s+OR\s+/).some(alt => alt.split(/\s+AND\s+/).every(id => ALLOWED.has(id.trim())));
}

function findPackageDir(dir, name) {
	// npm hoists, so look in the part's node_modules first, then walk known nested locations
	const direct = join(ROOT, dir, "node_modules", name);
	if (existsSync(join(direct, "package.json"))) {
		return direct;
	}
	return undefined;
}

function licenseText(pkgDir) {
	const file = readdirSync(pkgDir).find(f => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
	return file ? readFileSync(join(pkgDir, file), "utf8").trim() : undefined;
}

const problems = [];
const sections = [];
const texts = new Map(); // license text -> package ids
for (const part of PARTS) {
	const pkgs = new Map();
	collect(npm(part.dir, part.args), pkgs);
	const rows = [];
	for (const { name, version } of [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name))) {
		const pkgDir = findPackageDir(part.dir, name);
		const meta = pkgDir ? JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")) : {};
		const reviewed = REVIEWED[`${name}@${version}`];
		const license = reviewed ?? licenseOf(meta);
		if (!reviewed && !allowed(license)) {
			problems.push(`${part.name}: ${name}@${version} has license "${license}"`);
		}
		rows.push(`| ${name} | ${version} | ${license} |`);
		const text = pkgDir ? licenseText(pkgDir) : undefined;
		if (text) {
			const ids = texts.get(text) ?? [];
			ids.push(`${name}@${version}`);
			texts.set(text, ids);
		}
	}
	sections.push(`## ${part.name}\n\n| Package | Version | License |\n|---|---|---|\n${rows.join("\n")}\n`);
}

const md = [
	"# Third-party notices",
	"",
	"ioBroker.energyflow (GPL-3.0-only) includes or depends on the following third-party software.",
	"This file is generated by `node tools/generate-notices.mjs` - do not edit by hand.",
	"",
	"Data services used at runtime (not bundled) and other credits are listed in the README",
	'("Credits & attributions").',
	"",
	...sections,
	"## License texts",
	"",
	...[...texts.entries()].map(([text, ids]) => `### ${ids.join(", ")}\n\n\`\`\`text\n${text}\n\`\`\`\n`),
].join("\n");

if (problems.length) {
	console.error(`License check failed:\n${problems.join("\n")}`);
	process.exit(1);
}
if (!process.argv.includes("--check")) {
	writeFileSync(join(ROOT, "THIRD_PARTY_NOTICES.md"), md);
	for (const target of ["widgets/energyflow", "www"]) {
		if (existsSync(join(ROOT, target))) {
			copyFileSync(join(ROOT, "THIRD_PARTY_NOTICES.md"), join(ROOT, target, "THIRD_PARTY_NOTICES.md"));
		}
	}
}
console.log(`ok - ${texts.size} distinct license texts`);
